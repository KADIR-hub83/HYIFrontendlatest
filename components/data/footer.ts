// ========================
// Big Menus (header ke groups + sub-links)
// ========================

const buildMega = (value: string, exclude: string[] = []): MegaMenu => {
  const nav = getNav(value);
  return {
    key: value,
    heading: nav?.heading ?? nav?.title ?? value,
    paragraph: nav?.paragraph,
    groups: getGroups(value, exclude),
  };
};

